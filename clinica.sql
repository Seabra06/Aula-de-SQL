CREATE TABLE PACIENTE(
ID_PAC INT PRIMARY KEY NOT NULL IDENTITY,
NOME_PAC VARCHAR (100) NOT NULL,
EMAIL_PAC VARCHAR (150) UNIQUE,
TEL_PAC VARCHAR(15),
DT_NASC_PAC DATE
);
GO
