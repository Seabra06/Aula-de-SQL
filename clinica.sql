CREATE TABLE DENTISTA (
ID_DENT INT PRIMARY KEY,
NUM_CRO INT NOT NULL,
NOME_DENT VARCHAR (100) NOT NULL,
TEL_DENT VARCHAR (15) NOT NULL,
END_DENT VARCHAR (150)
);
GO
 


 CREATE TABLE CONSULTA(
 ID_CONSUL INT PRIMARY KEY,
 VALOR_CONSUL DECIMAL NOT NULL,
 DATE_CONSUL DATE,
 HORA_CONSUL DATETIME,
 FK_ID_DENT INT,
 FK_ID_PAC INT,
 FOREIGN KEY (FK_ID_DENT) REFERENCES DENTISTA (ID_DENT),
 FOREIGN KEY (FK_ID_PAC) REFERENCES PACIENTE (ID_PAC)
 );
 GO
